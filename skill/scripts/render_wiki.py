#!/usr/bin/env python3
"""Renders a document-anything Markdown file into a single self-contained HTML page (CSS and JS inline, Mermaid from CDN).

Usage:
    python render_wiki.py docs/wiki/my-service.md                 # writes docs/wiki/my-service.html
    python render_wiki.py docs/wiki/my-service.md -o out.html
    python render_wiki.py docs/wiki/my-service.md --check         # exit 1 when the HTML is missing or stale
    python render_wiki.py legacy.md --tags "PRW,Service,Hmpt"     # tags for a file without front matter

The output is deterministic: the same Markdown always produces the same HTML.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import wikilib  # noqa: E402

ASSETS = Path(__file__).resolve().parent.parent / "assets"
MERMAID_CDN = "https://cdn.jsdelivr.net/npm/mermaid@10.9.1/dist/mermaid.min.js"

UI = {
    "pt-BR": {
        "toc": "Sumário", "search": "Buscar no documento…",
        "view_label": "Filtrar visão", "expand": "Expandir tudo", "collapse": "Recolher tudo", "theme": "◐ Tema",
        "theme_label": "Alternar tema", "top": "Voltar ao topo", "updated": "Atualizado em", "commit": "commit",
        "generated": "Gerado por {gen} a partir de <code>{src}</code>. O Markdown é a fonte; edite-o e gere esta página novamente.",
        "found": "{s} seção(ões) · {n} ocorrência(s)", "notFound": "Nada encontrado", "copy": "Copiar", "copied": "Copiado",
    },
    "en": {
        "toc": "Contents", "search": "Search the document…",
        "view_label": "Filter view", "expand": "Expand all", "collapse": "Collapse all", "theme": "◐ Theme",
        "theme_label": "Toggle theme", "top": "Back to top", "updated": "Updated on", "commit": "commit",
        "generated": "Generated by {gen} from <code>{src}</code>. The Markdown is the source; edit it and render this page again.",
        "found": "{s} section(s) · {n} match(es)", "notFound": "Nothing found", "copy": "Copy", "copied": "Copied",
    },
}


def ui_for(lang: str) -> dict:
    return UI["pt-BR"] if lang.lower().startswith("pt") else UI["en"]


def view_labels(meta: dict, lang: str) -> list[str]:
    """Labels of the All / overview / detail filter, from the document type's blueprint."""
    key = wikilib.lang_key(lang)
    try:
        return wikilib.load_blueprint(str(meta.get("type") or "service"))["view_labels"][key]
    except KeyError:
        return ["Tudo", "Visão geral", "Detalhe"] if key == "pt-BR" else ["All", "Overview", "Detail"]


def format_date(value: str, lang: str) -> str:
    m = re.match(r"^(\d{4})-(\d{2})-(\d{2})$", value or "")
    if not m:
        return value or ""
    return f"{m.group(3)}/{m.group(2)}/{m.group(1)}" if lang.lower().startswith("pt") else value


def toc_html(toc: list[dict]) -> str:
    items = []
    for entry in toc:
        children = "".join(
            f'<li class="l2"><a href="#{wikilib.esc_attr(c["id"])}">{wikilib.esc(c["text"])}</a></li>'
            for c in entry["children"]
        )
        sub = f'<ul class="toc-l2">{children}</ul>' if children else ""
        if entry["id"]:
            items.append(f'<li class="l1"><a href="#{wikilib.esc_attr(entry["id"])}">{wikilib.esc(entry["text"])}</a>{sub}</li>')
        else:
            items.append(f'<li class="l1">{sub}</li>')
    return f'<ul class="toc-l1">{"".join(items)}</ul>'


def build_page(md_text: str, source_name: str, tags=None) -> str:
    doc = wikilib.render_document(md_text, tags=tags)
    meta = doc.meta
    lang = str(meta.get("lang") or "pt-BR")
    ui = ui_for(lang)
    title = doc.title or source_name
    subtitle = str(meta.get("subtitle") or "")
    stamp = []
    if meta.get("as_of"):
        stamp.append(f'{ui["updated"]} {wikilib.esc(format_date(str(meta["as_of"]), lang))}')
    if meta.get("source_commit"):
        stamp.append(f'{ui["commit"]} <code>{wikilib.esc(str(meta["source_commit"]))}</code>')
    i18n = json.dumps({k: ui[k] for k in ("found", "notFound", "copy", "copied")}, ensure_ascii=False).replace("</", "<\\/")
    css = (ASSETS / "wiki.css").read_text(encoding="utf-8")
    js = (ASSETS / "wiki.js").read_text(encoding="utf-8")
    mermaid = f'<script src="{MERMAID_CDN}"></script>\n' if doc.mermaid else ""
    generator = f"document-anything {wikilib.VERSION}"
    footer = ui["generated"].format(gen=generator, src=wikilib.esc(source_name))
    views = view_labels(meta, lang)
    e = wikilib.esc
    return f"""<!doctype html>
<html lang="{wikilib.esc_attr(lang)}">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="generator" content="{generator}">
<meta name="wiki-source" content="{wikilib.esc_attr(source_name)}">
<meta name="wiki-source-sha256" content="{wikilib.source_digest(md_text)}">
<title>{e(title)}</title>
<style>
{css}</style>
</head>
<body>
<div class="topbar">
  <button class="btn" id="navToggle" aria-label="{ui["toc"]}">☰ {ui["toc"]}</button>
  <span class="title">{e(title)}</span>
</div>
<div class="layout">
  <aside class="sidebar" id="sidebar">
    <div class="brand">{e(title)}</div>
    {f'<div class="brand-sub">{e(subtitle)}</div>' if subtitle else ''}
    {f'<div class="brand-meta">{" · ".join(stamp)}</div>' if stamp else ''}
    <div class="controls">
      <div class="search">
        <input id="q" type="search" placeholder="{ui["search"]}" autocomplete="off" aria-label="{ui["search"]}">
        <div class="search-info" id="searchInfo"></div>
      </div>
      <div class="seg" role="group" aria-label="{ui["view_label"]}">
        <button data-view="all" aria-pressed="true">{views[0]}</button>
        <button data-view="overview" aria-pressed="false">{views[1]}</button>
        <button data-view="detail" aria-pressed="false">{views[2]}</button>
      </div>
      <div class="row-btns">
        <button class="btn" id="expandAll">{ui["expand"]}</button>
        <button class="btn" id="collapseAll">{ui["collapse"]}</button>
        <button class="btn" id="themeBtn" aria-label="{ui["theme_label"]}">{ui["theme"]}</button>
      </div>
    </div>
    <nav class="toc" id="toc">{toc_html(doc.toc)}</nav>
  </aside>
  <main id="content">
{doc.body_html}
<footer class="doc-footer">{footer}</footer>
  </main>
</div>
<button class="to-top" id="toTop" aria-label="{ui["top"]}">↑</button>
<script>window.WIKI_I18N = {i18n};</script>
{mermaid}<script>
{js}</script>
</body>
</html>
"""


def html_digest(html_text: str) -> str | None:
    m = re.search(r'<meta name="wiki-source-sha256" content="([0-9a-f]{64})">', html_text)
    return m.group(1) if m else None


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("markdown", type=Path)
    parser.add_argument("-o", "--output", type=Path, help="HTML path (default: same name, .html)")
    parser.add_argument("--check", action="store_true", help="only verify the HTML matches the Markdown")
    parser.add_argument("--tags", help="comma-separated tags, overriding the front matter")
    sys.stdout.reconfigure(encoding="utf-8")
    args = parser.parse_args(argv)

    md_path: Path = args.markdown
    if not md_path.is_file():
        print(f"ERROR: {md_path} not found", file=sys.stderr)
        return 2
    out_path = args.output or md_path.with_suffix(".html")
    md_text = md_path.read_text(encoding="utf-8")

    if args.check:
        if not out_path.is_file():
            print(f"FAIL: {out_path} does not exist; run render_wiki.py {md_path}")
            return 1
        if html_digest(out_path.read_text(encoding="utf-8")) != wikilib.source_digest(md_text):
            print(f"FAIL: {out_path} is stale; run render_wiki.py {md_path}")
            return 1
        print(f"OK: {out_path.name} is in sync with {md_path.name}")
        return 0

    tags = wikilib.as_list(args.tags) if args.tags is not None else None
    page = build_page(md_text, md_path.name, tags)
    out_path.write_text(page, encoding="utf-8", newline="\n")
    print(f"OK: wrote {out_path} ({len(page.encode('utf-8')) // 1024} KB)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
